/**
 * UI language: English or Brazilian Portuguese.
 *
 * Hand-rolled rather than next-intl/react-intl on purpose — this is a
 * two-language, single-user app, and a dictionary object plus a context
 * provider is the whole feature. Adding an i18n framework would be a
 * dependency the owner has to reason about later for no gain here.
 *
 * The English dictionary is the source of truth for the *shape*: `pt` is typed
 * as `Dict`, so forgetting a key there is a compile error rather than a stray
 * English string discovered in the running app. Keep both objects in the same
 * key order so they stay diffable side by side.
 *
 * What is NOT translated, deliberately:
 * - The owner's own data — category names, payment methods, entry names,
 *   holding names, the goal name. That's her text, in whatever language she
 *   typed it.
 * - Currency. `formatCurrency` stays pt-BR/BRL in both languages, because the
 *   money is Brazilian whatever the interface language is.
 * - Brazilian product names in the investment taxonomy (CDB, LCI, Poupança,
 *   Tesouro IPCA+…), for the same reason they were left in Portuguese during
 *   the V1.20 English audit: those are what the statements say.
 */

export const LANGUAGES = [
  { value: "en", label: "English" },
  { value: "pt", label: "Português" },
] as const;

export type Language = (typeof LANGUAGES)[number]["value"];

export const DEFAULT_LANGUAGE: Language = "en";

/** Anything unrecognized falls back to English rather than rendering blanks. */
export function clampLanguage(value: string | null | undefined): Language {
  return LANGUAGES.some((l) => l.value === value) ? (value as Language) : DEFAULT_LANGUAGE;
}

/**
 * The `Intl` locale used for month and weekday names. Currency deliberately
 * does not go through this — see the note above.
 */
export function localeOf(lang: Language): string {
  return lang === "pt" ? "pt-BR" : "en-US";
}

